'use strict';

// Deterministic instruction-provenance nudge for dispatches that adopt
// instructions, prompts, skills, templates, or workflows written by someone
// other than the operator. Inspired by Jake Van Clief's instruction-provenance
// lesson (video u9h7YszlKhM, concept ai-is-part-of-a-program): an instruction
// slot carries an authorship question, not just a content question. When the
// instructions were written by an AI or another programmer, the work follows
// their rules and their opinion. Operating rule: own the opinionated
// instructions (procedure, subject/identity, verb scope); rent only the
// non-opinionated connectors/runtimes/tooling.
//
// Distinct from portable-instruction-asset (is the workflow package portable
// out of the wrapper?) and opinion-standard (is taste encoded as reviewable
// material?). This fires when a dispatch is about to run inherited/borrowed
// instructions and has not said whose opinion those instructions carry.

const INHERITED_INSTRUCTION_TERMS = [
  'based on', 'build on', 'building on', 'from the docs', 'from their docs',
  'from this repo', 'from the repo', 'from the template', 'copy', 'copied',
  'copying', 'clone', 'cloned', 'cloning', 'reuse', 'reused', 'reusing',
  're-use', 'borrow', 'borrowed', 'borrowing', 'inherit', 'inherited',
  'inheriting', 'adopt', 'adopted', 'adopting', 'adapt', 'adapted', 'adapting',
  'scaffold', 'scaffolded', 'scaffolding', 'boilerplate', 'template', 'templates',
  'follow this', 'follow the', 'follow their', 'use this prompt', 'use the prompt',
  'use this', 'use their', 'third-party', 'third party', 'vendor', 'vendored',
  'off-the-shelf', 'off the shelf', 'someone else', 'existing prompt',
  'existing skill', 'existing workflow', 'generated by', 'written by',
  'came with', 'comes with', 'provided prompt', 'out of the box'
];

// The instruction object: something that tells a runner what to do.
const INSTRUCTION_OBJECT_TERMS = [
  'prompt', 'prompts', 'skill', 'skills', 'instruction', 'instructions',
  'template', 'templates', 'sop', 'sops', 'playbook', 'playbooks', 'workflow',
  'workflows', 'rules', 'rulebook', 'guidelines', 'guideline', 'style guide',
  'conventions', 'convention', 'spec', 'specs', 'charter', 'personality',
  'system prompt', 'readme', 'claude.md', 'agents.md', 'skill.md', 'rubric',
  'context file', 'context files', 'procedure', 'checklist', 'runbook'
];

// If enough of these are present, the provenance question is already framed,
// so we should not nag.
const FRAMED_TERMS = [
  'provenance', 'authored', 'authorship', 'written by', 'we wrote', 'our own',
  'own the', 'we own', 'who wrote', 'in-house', 'in house', 'opinionated',
  'non-opinionated', 'non opinionated', 'instruction provenance', 'authored by'
];

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Word-boundary matching so short tokens cannot false-match inside other words.
function countMatches(text, terms) {
  return terms.reduce(function (count, term) {
    const pattern = new RegExp('\\b' + escapeRegExp(term) + '\\b');
    return pattern.test(text) ? count + 1 : count;
  }, 0);
}

function classifyInstructionProvenance(message) {
  const text = String(message || '').toLowerCase();
  if (!text.trim()) {
    return { applies: false, reason: 'empty message', score: 0 };
  }

  const inherited = countMatches(text, INHERITED_INSTRUCTION_TERMS);
  const instructionObject = countMatches(text, INSTRUCTION_OBJECT_TERMS);
  const framed = countMatches(text, FRAMED_TERMS);
  const score = (inherited * 3) + (instructionObject * 2);

  if (inherited === 0) {
    return { applies: false, reason: 'no inherited/borrowed-instruction signal', score };
  }
  if (instructionObject === 0) {
    return { applies: false, reason: 'inheritance signal without an instruction object', score };
  }
  if (framed >= 2) {
    return { applies: false, reason: 'instruction provenance already framed', score };
  }
  if (score < 5) {
    return { applies: false, reason: 'weak instruction-provenance signal', score };
  }

  const layer = instructionObject >= 2
    ? 'multi-instruction-adoption'
    : 'single-instruction-adoption';

  return {
    applies: true,
    reason: 'instructions written by someone else are about to run; establish whose opinion they carry',
    score,
    layer,
    signals: { inherited, instructionObject, framed }
  };
}

function instructionProvenancePromptBlock(message) {
  const classification = classifyInstructionProvenance(message);
  if (!classification.applies) return '';

  return '[INSTRUCTION PROVENANCE CHECK]\n'
    + 'This dispatch is about to run instructions that were written by someone other than the operator. Instructions carry authorship, not just content — whoever wrote them decides the rules the work follows and the opinion it produces. Name the provenance before running them. Keep this brief and then continue the task.\n'
    + '- Instruction author: name who wrote each instruction set in play (the operator, another agent, a vendor, a template/repo, an unknown source). If authorship cannot be established from the files, say so as a limitation — do not assume the operator wrote it.\n'
    + '- Opinionated parts: the procedure, the subject/identity (whose data, which person, what counts as the subject), and the scope of the verb. These encode opinion and must be owned here — restate them in the operator\'s terms.\n'
    + '- Non-opinionated parts: connectors, runtimes, tooling, and format plumbing are rentable — take them from whoever does them best and do not rewrite them for ownership\'s sake.\n'
    + '- Verb scope: define what the instruction actually asks for (what "check", "review", "fix", "summarize" means here, over which objects, with what output) before handing it to a runner.\n'
    + '- Drift audit: when output is off-spec or off-brand, check instruction provenance before blaming the model — borrowed instructions silently import someone else\'s opinion.\n'
    + '- Verdict: keep-and-own the instruction as the operator\'s / rewrite the opinionated parts in the operator\'s terms / rent only the non-opinionated connectors. Never let a borrowed instruction silently define the opinion.\n'
    + '[/INSTRUCTION PROVENANCE CHECK]';
}

function appendInstructionProvenancePrompt(message) {
  const block = instructionProvenancePromptBlock(message);
  if (!block) return String(message || '');
  return String(message || '') + '\n\n' + block;
}

module.exports = {
  classifyInstructionProvenance,
  instructionProvenancePromptBlock,
  appendInstructionProvenancePrompt
};
